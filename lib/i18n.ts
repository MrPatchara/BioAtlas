export const STR: Record<Lang, typeof en> = { en, th };

export function loadLang(): Lang {
  try {
    return localStorage.getItem('bioatlas-lang') === 'th' ? 'th' : 'en';
  } catch {
    return 'en';
  }
}

export function saveLang(lang: Lang) {
  try {
    localStorage.setItem('bioatlas-lang', lang);
  } catch {
    /* private mode */
  }
}
